// Generates supabase/seed.sql from @thiqa/core + seed-data.ts.
// Idempotent SQL (upserts): safe to re-run, including on production.
// Usage: pnpm db:seed:gen   (a test fails if the committed file is stale)

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  CITIES,
  IDS,
  NOTIFICATION_TEMPLATES,
  PAYOUT_RULES,
  PRICING_RULES,
  PRODUCTS,
  SECTORS,
  TEMPLATE,
  WORKS,
} from './seed-data';

export const SEED_PATH = fileURLToPath(new URL('../../../supabase/seed.sql', import.meta.url));

const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const n = (v: number | null | undefined) => (v == null ? 'null' : String(v));
const arr = (v: readonly string[]) => `array[${v.map(q).join(', ')}]::text[]`;
const rows = (r: string[]) => r.map((x) => `  (${x})`).join(',\n');

export function buildSeed(): string {
  const out: string[] = [
    '-- GENERATED by packages/db/scripts/gen-seed.ts — do not edit by hand.',
    '-- Reference data: cities, sectors, checklist template v1, products, pricing,',
    '-- works catalog, payout rules, notification templates. Idempotent.',
    '',
    'begin;',
    '',
    'insert into public.cities (id, name, slug, active, bbox) values',
    rows(
      CITIES.map(
        (c) =>
          `${q(c.id)}, ${q(c.name)}, ${q(c.slug)}, ${c.active}, st_geomfromtext(${q(c.bbox)}, 4326)`,
      ),
    ),
    'on conflict (id) do update set name = excluded.name, slug = excluded.slug, bbox = excluded.bbox;',
    '',
    'insert into public.sectors (id, city_id, name, slug, polygon) values',
    rows(
      SECTORS.map(
        (s) =>
          `${q(s.id)}, ${q(s.city_id)}, ${q(s.name)}, ${q(s.slug)}, st_geogfromtext(${q(`SRID=4326;${s.wkt}`)})`,
      ),
    ),
    'on conflict (id) do update set name = excluded.name, polygon = excluded.polygon;',
    '',
    `-- Checklist template ${TEMPLATE.key} v${TEMPLATE.version}: ${TEMPLATE.schema.items.length} items.`,
    'insert into public.checklist_templates (id, key, version, schema, published_at) values',
    rows([
      `${q(TEMPLATE.id)}, ${q(TEMPLATE.key)}, ${TEMPLATE.version}, ${j(TEMPLATE.schema)}, now()`,
    ]),
    'on conflict (key, version) do nothing;',
    '',
    'insert into public.products (id, slug, name_i18n, description_i18n, base_price_mad, duration_min, checklist_template_id, required_skills, options, active, sort_order) values',
    rows(
      PRODUCTS.map(
        (p) =>
          `${q(p.id)}, ${q(p.slug)}, ${j(p.name_i18n)}, ${j(p.description_i18n)}, ${p.base_price_mad}, ${p.duration_min}, ${q(IDS.template.v1)}, ${arr(p.required_skills)}, ${j(p.options)}, ${p.active}, ${p.sort_order}`,
      ),
    ),
    'on conflict (id) do update set name_i18n = excluded.name_i18n, description_i18n = excluded.description_i18n,',
    '  required_skills = excluded.required_skills, options = excluded.options, checklist_template_id = excluded.checklist_template_id;',
    '',
    '-- Pricing rules apply to every product (product_id null) unless overridden.',
    `delete from public.pricing_rules where product_id is null and city_id is null and label in (${PRICING_RULES.map((r) => q(r.label)).join(', ')});`,
    'insert into public.pricing_rules (label, surface_min, surface_max, property_type, multiplier) values',
    rows(
      PRICING_RULES.map(
        (r) =>
          `${q(r.label)}, ${n(r.surface_min)}, ${n(r.surface_max)}, ${r.property_type ? `${q(r.property_type)}::public.property_type` : 'null'}, ${r.multiplier}`,
      ),
    ),
    ';',
    '',
    '-- National baseline works catalog (city_id null); per-city overrides are added in the back-office.',
    'insert into public.works_catalog (city_id, code, label_i18n, unit, min_mad, max_mad) values',
    rows(
      WORKS.map(
        (w) =>
          `null, ${q(w.code)}, ${j({ fr: w.label_fr })}, ${q(w.unit)}, ${w.min_mad}, ${w.max_mad}`,
      ),
    ),
    "on conflict (coalesce(city_id, '00000000-0000-0000-0000-000000000000'::uuid), code) do update",
    '  set label_i18n = excluded.label_i18n, unit = excluded.unit, min_mad = excluded.min_mad, max_mad = excluded.max_mad;',
    '',
    `delete from public.payout_rules where city_id is null and product_id in (${PAYOUT_RULES.map((r) => q(r.product_id)).join(', ')});`,
    'insert into public.payout_rules (product_id, fixed_mad, variable_pct, bonus_rules, valid_from) values',
    rows(
      PAYOUT_RULES.map(
        (r) =>
          `${q(r.product_id)}, ${r.fixed_mad}, ${r.variable_pct}, ${j(r.bonus_rules)}, date '2026-01-01'`,
      ),
    ),
    ';',
    '',
    'insert into public.notification_templates (key, channel, lang, version, subject, body) values',
    rows(
      NOTIFICATION_TEMPLATES.map(
        (t) =>
          `${q(t.key)}, ${q(t.channel)}::public.notification_channel, 'fr', 1, ${q(t.subject)}, ${q(t.body)}`,
      ),
    ),
    'on conflict (key, channel, lang, version) do update set subject = excluded.subject, body = excluded.body;',
    '',
    'commit;',
    '',
  ];
  return out.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(SEED_PATH, buildSeed());
  console.log(`wrote ${SEED_PATH}`);
}
